/*
Entity — базовый абстрактный класс для всех сущностей предметной области.

Назначение:
- Единая точка для общих полей и общих правил (идентификатор, имя).
- Служит основой для Company, Product, Order, MarketEvent и т.д.

Обязательные поля (записать как комментарии; реализация позже):
- String id                // уникальный идентификатор
- String name              // читаемое имя/название

Инварианты:
- id не пустой и уникален в соответствующем репозитории.
- name не пустой (если пуст — валидация вверх по стеку).

Публичные методы (словесно):
- describe() -> String     // возвращает человекочитаемое описание сущности

Сериализация:
- toMap() -> Map<String,dynamic>  // должен включать id, name и _schema/_version
- fromMap(Map) -> Entity (реализация в конкретных классах)

Ошибки/Result:
- При нарушении инвариантов реализация должна возвращать Result.fail("InvalidEntity:<reason>")

Примечания по реализации:
- Не класть в Entity логику, связанную с бизнес-правилами. Только общие данные.
- Не использовать print в этой прослойке — логи через Logger.
*/
class Entity {
    String id;
    String name;
    Entity(this.id, this.name);

    @override
  String toString() {
    return ''
    'id: $id'
    'name: $name'
    '';
  }
}
