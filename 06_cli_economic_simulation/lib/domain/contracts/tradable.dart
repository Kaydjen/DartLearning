/*
Contract: Tradable
Роль: контракт проверки допуска к сделкам и урегулирования завершённых исполнений.

Методы (описание, не реализация):
- canBuy(companyId, productSymbol, qty) -> Result
  Проверяет предварительно: существование компании и продукта, qty>0, баланс >= цена*qty+fee.
  Возвращает Result.ok() или Result.fail(reason).

- canSell(companyId, productSymbol, qty) -> Result
  Проверяет: qty>0, компания владеет достаточным количеством продукта.

- settleTrade(order, executionPrice, executedQty) -> Result
  Выполняет: списание/зачисление балансов, изменение портфеля, учёт комиссии, изменение статуса ордера.
  Публикует соответствующие события через EventBus (OrderFilled/PartiallyFilled).

Замечания:
- Все операции, изменяющие состояние, должны возвращать Result и оставлять систему в валидном состоянии.
- Реализация должна быть атомарной (validate → reserve → commit → publish), либо обеспечить откат.
*/
